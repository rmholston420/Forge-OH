#!/usr/bin/env python3
"""Pack a bench_f19pre run dir into one comparative markdown file for judging.
Usage: pack_results.py <run_dir> [--out <file.md>]
"""
import argparse, json, sys
from pathlib import Path

CELL_ORDER = ["c01","c02","c03","c04","c05","c06","c07","c08"]
PROMPT_ORDER = ["debug","arch","plan"]
CELL_LABELS = {
    "c01": "c01 Coder / Ollama / qwen3-coder:30b (Q4_K_M)",
    "c02": "c02 Coder / vLLM / qwen3-coder-30b-awq (compressed-tensors)",
    "c03": "c03 Coder / Ollama / qwen3.6:35b-a3b think:false (Q4_K_M)",
    "c04": "c04 Coder / vLLM / qwen3.6-35b-nvfp4 (modelopt_fp4)",
    "c05": "c05 Planner / Ollama / qwen3.6:35b-a3b think:true (Q4_K_M)",
    "c06": "c06 Planner / vLLM / qwen3.6-35b-nvfp4 think:true (modelopt_fp4)",
    "c07": "c07 Planner / Ollama / qwen3-thinking-2507:q4kxl (Q4_K_XL GGUF)",
    "c08": "c08 Planner / vLLM / qwen3-thinking-2507-awq (compressed-tensors)",
}
PROMPT_TITLES = {
    "debug": "Prompt 1 — debug.txt: RBAC ImportError diagnosis after Step-2 deletion",
    "arch":  "Prompt 2 — arch.txt: openhands_client.py duplicate resolution",
    "plan":  "Prompt 3 — plan.txt: Step-3 vertical slice commit sequence",
}

def load(run_dir):
    results = {}
    for fp in run_dir.glob("*.json"):
        if fp.name == "manifest.json":
            continue
        stem = fp.stem  # c02__debug
        try:
            cell, prompt = stem.split("__", 1)
        except ValueError:
            continue
        results.setdefault(prompt, {})[cell] = json.loads(fp.read_text())
    return results

def fmt_metrics(r):
    if "error" in r:
        return f"**ERROR:** {r['error'][:200]}"
    return (
        f"- Latency (min/med/max): {r['latency_min_s']:.2f}s / {r['latency_med_s']:.2f}s / {r['latency_max_s']:.2f}s\n"
        f"- Completion tokens: {r['completion_tokens']}  |  Tokens/s (median): {r['tokens_per_s_med']}\n"
        f"- Finish reason: `{r['finish_reason']}`\n"
    )

def fmt_answer(r):
    if "error" in r:
        return "_(no answer — error above)_\n"
    parts = []
    if r.get("reasoning_content"):
        parts.append(f"<details><summary>reasoning_content ({len(r['reasoning_content'])} chars)</summary>\n\n```\n{r['reasoning_content']}\n```\n\n</details>\n")
    parts.append(r.get("content", "").strip() or "_(empty content)_")
    return "\n".join(parts) + "\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    run_dir = Path(args.run_dir).expanduser()
    if not run_dir.is_dir():
        print(f"not a dir: {run_dir}", file=sys.stderr); sys.exit(2)

    results = load(run_dir)
    manifest = (run_dir / "manifest.json")
    ts = ""
    if manifest.exists():
        ts = json.loads(manifest.read_text()).get("ts", "")

    out_path = Path(args.out) if args.out else (
        Path.home() / "dev" / "forge-oh" / "bench" / "f19pre" / "results" / f"bench_f19pre_{ts or 'run'}.md"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)

    lines = []
    lines.append(f"# F.19-pre Bench Results — {ts}\n")
    lines.append("Generated by `pack_results.py`. Each prompt section shows all 8 candidate answers side-by-side for comparative judging.\n")
    lines.append(f"Source run dir on Colossus: `{run_dir}`\n")
    lines.append("---\n")

    for prompt in PROMPT_ORDER:
        if prompt not in results:
            continue
        lines.append(f"## {PROMPT_TITLES[prompt]}\n")
        prompt_text = (Path.home() / "dev" / "forge-oh" / "bench" / "prompts" / f"{prompt}.txt").read_text()
        lines.append(f"<details><summary>Task text (verbatim)</summary>\n\n```\n{prompt_text}\n```\n\n</details>\n")
        for cell in CELL_ORDER:
            if cell not in results[prompt]:
                lines.append(f"### {CELL_LABELS[cell]}\n\n_(no data for this cell)_\n")
                continue
            r = results[prompt][cell]
            lines.append(f"### {CELL_LABELS[cell]}\n")
            lines.append(fmt_metrics(r))
            lines.append("\n**Answer:**\n")
            lines.append(fmt_answer(r))
            lines.append("---\n")

    out_path.write_text("\n".join(lines))
    print(f"WROTE: {out_path}")
    print(f"Size: {out_path.stat().st_size} bytes")

if __name__ == "__main__":
    main()
